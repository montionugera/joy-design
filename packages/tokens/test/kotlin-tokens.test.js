import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const scriptPath = path.join(__dirname, '../scripts/gen-kotlin-tokens.mjs');
const generatedPath = path.join(
  __dirname,
  '../../kotlin/src/main/kotlin/com/joymify/design/JoyTokens.g.kt',
);

test('Kotlin token generator produces JoyTokens.g.kt and passes --check', () => {
  execFileSync('node', [scriptPath, '--check'], { stdio: 'pipe' });
  assert.ok(fs.existsSync(generatedPath), 'JoyTokens.g.kt must exist');

  const content = fs.readFileSync(generatedPath, 'utf8');
  assert.ok(content.includes('package com.joymify.design'), 'must declare package com.joymify.design');
  assert.ok(
    content.includes('import androidx.compose.ui.graphics.Color'),
    'must import androidx.compose.ui.graphics.Color',
  );
  assert.ok(
    content.includes('// DO NOT EDIT \u2014 generated by packages/tokens/scripts/gen-kotlin-tokens.mjs'),
    'must emit DO NOT EDIT header',
  );

  // Only androidx.compose.ui.graphics.Color import (zero extra Compose imports)
  const imports = content.match(/^import\s+.+$/gm) || [];
  assert.deepStrictEqual(
    imports,
    ['import androidx.compose.ui.graphics.Color'],
    'must only import androidx.compose.ui.graphics.Color',
  );

  for (const symbol of [
    'object JoyPalette',
    'val navy800 = Color(0xFF111B2B)',
    'data class JoyThemeTokens(',
    'val light: JoyThemeTokens',
    'val dark: JoyThemeTokens',
    'val modernLight: JoyThemeTokens',
    'val modernDark: JoyThemeTokens',
    'fun modern(isDark: Boolean = false): JoyThemeTokens',
    'data class JoyGradientStop(',
    'object JoyModernTokens',
    'const val firstLightAngleDeg: Float = 172f',
    'val firstLightStops: List<JoyGradientStop>',
    'object JoySpacing',
    'object JoyRadii',
    'object JoyTypography',
  ]) {
    assert.ok(content.includes(symbol), `JoyTokens.g.kt must emit ${symbol}`);
  }

  // Modern Midnight Brass, First Light 6-stop sky gradient, and Kintsugi seam fields + hex values
  for (const field of [
    'val canvas:',
    'val card:',
    'val tile:',
    'val border:',
    'val title:',
    'val text:',
    'val skyInk:',
    'val button:',
    'val buttonText:',
    'val buttonEdge:',
    'val porcelain:',
    'val porcelainText:',
    'val mutedTint:',
    'val successTint:',
    'val errorTint:',
    'val seamMid:',
    'val seamEdge:',
    'val ivoryCore:',
  ]) {
    assert.ok(content.includes(field), `JoyModernTokens must expose ${field}`);
  }

  for (const hexLiteral of [
    '0xFF0A121F',
    '0xFF111B2B',
    '0xFF14253E',
    '0xFF223250',
    '0xFFEEF2F8',
    '0xFFD5DBE6',
    '0xFFA9B4C6',
    '0xFFDAB362',
    '0xFF150B00',
    '0xFFA5802B',
    '0xFFF3F5F9',
    '0xFF4E5F7B',
    '0xFF93C794',
    '0xFFFB9890',
    '0xFFF0CC7A',
    '0xFFB8892B',
    '0xFFE0B03A',
    '0xFFAE7D0E',
    '0xFFFBF3E9',
    '0xFF0B1226',
    '0xFF101B38',
    '0xFF2A2014',
    '0xFF4A2A14',
    '0xFFC7743F',
    '0xFFF2C078',
  ]) {
    assert.ok(
      content.includes(`Color(${hexLiteral})`),
      `JoyTokens.g.kt must emit Color(${hexLiteral})`,
    );
  }

  // Verify all 6 First Light gradient stop positions for dark and light modes
  for (const pos of ['0.00f', '0.46f', '0.56f', '0.63f', '0.80f', '0.52f', '0.61f', '0.68f', '0.86f', '1.00f']) {
    assert.ok(content.includes(`position = ${pos}`), `JoyTokens.g.kt must emit gradient stop position ${pos}`);
  }
});
