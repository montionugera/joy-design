// Pure markdown rendering for scripts/gen-design-md.mjs. Every number comes from the model;
// the prose here is the fixed rule text. Output is deterministic: no dates, stable ordering.

const HEX = /^#[0-9a-fA-F]{3,8}$/;
const q = (v) => `"${String(v).replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
const table = (head, rows) =>
  [`| ${head.join(' | ')} |`, `| ${head.map(() => '---').join(' | ')} |`, ...rows.map((r) => `| ${r.join(' | ')} |`)].join('\n');
const code = (v) => `\`${v}\``;
const get = (entries, key) => {
  const hit = entries.find(([k]) => k === key);
  if (!hit) throw new Error(`gen-design-md: token ${key} missing`);
  return hit[1];
};

export const GENERATED_NOTE = '<!-- Generated by scripts/gen-design-md.mjs from packages/tokens. Do not edit by hand; run `node scripts/gen-design-md.mjs`. -->';

// Stitch typography roles mapped onto the token scale.
const TYPE_ROLES = [
  ['display', '5xl', 'bold', 'tight', 'tight'],
  ['headline', '3xl', 'semibold', 'tight', 'tight'],
  ['title', 'xl', 'semibold', 'snug', 'normal'],
  ['body', 'md', 'regular', 'normal', 'normal'],
  ['label', 'sm', 'medium', 'normal', 'normal'],
  ['caption', 'xs', 'regular', 'normal', 'normal']
];

function frontmatter(m) {
  const lines = ['---', 'name: Joymify Design System', `description: ${q('One token-driven design system that renders identically in Svelte and React, in light and dark, on desktop and phone.')}`, 'colors:'];
  for (const [ramp, step] of [['navy', '500'], ['gold', '400'], ['cream', '100'], ['ink', '500']]) {
    lines.push(`  brand-${ramp}: ${q(m.primitive[ramp][step])}`);
  }
  for (const theme of ['light', 'dark']) {
    for (const [group, roles] of Object.entries(m.semantic[theme])) {
      for (const [role, { value }] of Object.entries(roles)) {
        if (!HEX.test(value)) continue;
        lines.push(`  ${[group, role].filter(Boolean).join('-')}${theme === 'dark' ? '-dark' : ''}: ${q(value)}`);
      }
    }
  }
  lines.push('typography:');
  const family = get(m.fontFamily, 'sans');
  for (const [role, size, weight, lh, ls] of TYPE_ROLES) {
    lines.push(
      `  ${role}:`,
      `    fontFamily: ${q(family)}`,
      `    fontSize: ${q(get(m.fontSize, size))}`,
      `    fontWeight: ${get(m.fontWeight, weight)}`,
      `    lineHeight: ${get(m.lineHeight, lh)}`,
      `    letterSpacing: ${q(get(m.letterSpacing, ls))}`
    );
  }
  lines.push('rounded:', ...m.radius.map(([k, v]) => `  ${k}: ${q(v)}`));
  lines.push('spacing:', ...m.space.map(([k, v]) => `  ${q(k)}: ${q(v)}`));
  const h = (k) => q(get(m.controlHeight, k));
  lines.push(
    'components:',
    '  button-primary:',
    '    backgroundColor: "{colors.accent-default}"',
    '    textColor: "{colors.text-on-accent}"',
    '    rounded: "{rounded.control}"',
    `    height: ${h('md')}`,
    '  button-primary-hover:',
    '    backgroundColor: "{colors.accent-hover}"',
    '  button-primary-active:',
    '    backgroundColor: "{colors.accent-active}"',
    '  input:',
    '    backgroundColor: "{colors.surface-card}"',
    '    textColor: "{colors.text-primary}"',
    '    rounded: "{rounded.control}"',
    `    height: ${h('md')}`,
    '  card:',
    '    backgroundColor: "{colors.surface-card}"',
    '    textColor: "{colors.text-primary}"',
    '    rounded: "{rounded.card}"',
    `    padding: ${q(get(m.space, '6'))}`,
    '---'
  );
  return lines.join('\n');
}

function overview(m) {
  return `## Overview

Joymify is a component library for task-focused apps (register: **product**); the landing suite (\`HeroSection\`, \`CTASection\`, \`PricingCard\`, \`LandingPage\` and friends) is designed in the **brand** register. Personality: **composed, exact, warm**. Dense where data demands it, calm everywhere else. Gold is a signature, not a wash. Product context lives in \`PRODUCT.md\`.

**Token contract.** Components read the semantic layer (\`--joy-surface-*\`, \`--joy-text-*\`, \`--joy-border-*\`, \`--joy-accent-*\`, \`--joy-status-*\`, \`--joy-focus-ring\`, \`--joy-elevation-*\`). Primitive ramps (\`--joy-color-*\`) only feed that layer. Colour literals live only in \`packages/tokens/src/tokens.json\`.

**Theme switching.** \`data-theme="dark"\` or \`data-theme="light"\` on \`<html>\` wins. Without it, \`prefers-color-scheme\` picks the theme. Both themes are designed: dark is not inverted light.

### Spacing

A 4px grid. Use the token, never the raw value.

${table(['Token', 'Value'], m.space.map(([k, v]) => [code(`--joy-space-${k}`), v]))}

### Z-index scale

One ordered scale; never a raw \`999\`.

${table(['Layer', 'Token', 'Value'], m.z.map(([k, v]) => [k, code(`--joy-z-${k}`), v]))}

### Motion

${table(['Token', 'Value'], [...m.duration.map(([k, v]) => [code(`--joy-duration-${k}`), v]), ...m.ease.map(([k, v]) => [code(`--joy-ease-${k}`), code(v)])])}

Transitions use these durations with \`--joy-ease-out\`. Animate \`transform\`, \`opacity\` and colour, never layout. Every animation has a \`prefers-reduced-motion: reduce\` branch.

### Mobile rules

- 375px is the first viewport: no horizontal scroll, grids collapse to one column, tables stack or scroll inside their own container.
- Touch targets are at least 44 x 44 CSS px on coarse pointers (buttons, inputs, checkboxes, tabs, pagination, close buttons).
- Side gutters are at least 16px. Input text is at least 16px so iOS does not zoom.
- Select-family overlays become a bottom sheet on small screens; hover-only affordances have a touch alternative.`;
}

function colors(m) {
  const ramps = Object.entries(m.primitive).map(([ramp, steps]) => {
    const prefix = ramp.startsWith('status-') ? `--joy-color-status-${ramp.slice(7)}` : `--joy-color-${ramp}`;
    return `**${ramp}**\n\n${table(['Step', 'Token', 'Value'], Object.entries(steps).map(([s, v]) => [s, code(`${prefix}-${s}`), code(v)]))}`;
  });
  const semanticRows = [];
  for (const [group, roles] of Object.entries(m.semantic.light)) {
    for (const [role, { cssVar, value }] of Object.entries(roles)) {
      semanticRows.push([code(cssVar), code(value), code(m.semantic.dark[group][role].value)]);
    }
  }
  const contrast = m.contrast.map((r) => [r.theme, code(r.fg), code(r.bg), r.ratio.toFixed(2), r.min === null ? 'info' : `${r.min}:1`, r.pass === null ? 'n/a' : r.pass ? 'pass' : 'FAIL']);
  return `## Colors

Four brand anchors: navy \`${m.primitive.navy['500']}\` (primary surface anchor), gold \`${m.primitive.gold['400']}\` (the single accent), cream \`${m.primitive.cream['100']}\` (warm canvas), ink \`${m.primitive.ink['500']}\` (primary text). Neutrals are tinted toward the brand, not slate.

### Semantic layer

The contract. Light and dark values for every role.

${table(['Token', 'Light', 'Dark'], semanticRows)}

### Measured contrast

WCAG 2.2 relative-luminance ratios computed from the values above (\`packages/tokens/scripts/color.mjs\`). The token contrast gate (\`packages/tokens/test/contrast.test.js\`) enforces AA in both themes.

${table(['Theme', 'Foreground', 'Background', 'Ratio', 'Minimum', 'Result'], contrast)}

### Primitive ramps

Inputs to the semantic layer. Components never reference these directly.

${ramps.join('\n\n')}`;
}

function typography(m) {
  return `## Typography

Sans: ${code(get(m.fontFamily, 'sans'))}. Mono (code, tabular data): ${code(get(m.fontFamily, 'mono'))}. A 1.2 modular scale from a 16px body.

${table(['Token', 'Size'], m.fontSize.map(([k, v]) => [code(`--joy-font-size-${k}`), v]))}

${table(['Token', 'Value'], [...m.fontWeight.map(([k, v]) => [code(`--joy-font-weight-${k}`), v]), ...m.lineHeight.map(([k, v]) => [code(`--joy-line-height-${k}`), v]), ...m.letterSpacing.map(([k, v]) => [code(`--joy-letter-spacing-${k}`), v])])}

Sentence case everywhere. Body line length stays at or under 75ch.`;
}

function elevation(m) {
  const rows = Object.keys(m.semantic.light.elevation).map((k) => [code(`--joy-elevation-${k}`), code(m.semantic.light.elevation[k].value), code(m.semantic.dark.elevation[k].value)]);
  return `## Elevation

Light theme lifts with soft navy-tinted shadows. Dark theme lifts with a hairline ring plus a deeper shadow, and raised surfaces get lighter, never a grey shadow on black.

${table(['Token', 'Light', 'Dark'], rows)}

### Radius roles

One radius per role.

${table(['Token', 'Value', 'Use'], m.radius.map(([k, v]) => [code(`--joy-radius-${k}`), v, { control: 'buttons, inputs, selects', card: 'cards, panels', overlay: 'modals, drawers, popovers', pill: 'tags, badges, switches' }[k] ?? '']))}

Focus: \`--joy-focus-ring\` (light \`${m.semantic.light['focus-ring'][''].value}\`, dark \`${m.semantic.dark['focus-ring'][''].value}\`) on \`:focus-visible\`, never \`outline: none\` without it.`;
}

function sizesCell(sizes) {
  if (sizes.length === 0) return '-';
  const out = [...sizes];
  if (!out.includes('md') && out.includes('sm') && out.includes('lg')) out.splice(out.indexOf('lg'), 0, 'md (default)');
  return out.join(', ');
}

function components(m) {
  const rows = m.componentMatrix.map((r) => [r.component, code(`.${r.cls}`), sizesCell(r.sizes), r.variants.length ? r.variants.join(', ') : '-', r.states.length ? r.states.join(', ') : '-']);
  return `## Components

Control heights: ${m.controlHeight.map(([k, v]) => `${k} ${v}`).join(', ')}. On coarse pointers every interactive control grows to a 44px target.

### State matrix

Read from the stylesheet (\`packages/tokens/dist/theme.css\`): for each component, the block classes its Svelte source emits and the states and size modifiers the stylesheet styles on them. Twins render the same classes in React (\`scripts/parity-check.mjs\`). \`md\` is the unmodified default where a component has \`sm\` and \`lg\`. A dash means the component is static or inherits its states from the controls it renders.

${table(['Component', 'Block', 'Sizes', 'Variants', 'States'], rows)}`;
}

function brand(m) {
  const roles = Object.keys(m.semantic.light.brand).map((role) => code(`--joy-brand-${role}`));
  return `## Brand

The mark is a gold diamond on a navy tile, not a square and not a circle: outline \`M16 4 28 16 16 28 4 16Z\`, inner fill \`M16 9 23 16 16 23 9 16Z\`, a centre dot, on a 32×32 tile with \`rx=6\`, defined once in \`packages/brand/src/geometry.js\`. The wordmark is "Joymify" in sentence case, set in the display font and converted to vector outlines (no live text, no font dependency at render time). The canonical mark : gap : glyph ratio is \`48 : 16 : 40\`. Components render the wordmark at padding 0, so the mark height equals the \`height\` prop and the glyph is drawn with \`overflow: visible\`, deliberately overflowing its box by about 8% of height on each edge; a parent that clips with \`overflow: hidden\` must add that padding back. Downloadable wordmark assets (\`packages/brand/assets/\`) bake in 16px padding at 80px height.

Display font: ${code('--joy-font-family-display')} (\`${get(m.fontFamily, 'display')}\`). joy-design does not load the font; consumers do.

Colour roles: ${roles.join(', ')} — light and dark values are in the [Semantic layer](#semantic-layer) table above.

### Don'ts

- Do not recolour the mark or wordmark outside the \`--joy-brand-*\` roles above.
- Do not stretch or skew the mark or wordmark; scale it uniformly.
- Do not substitute the square mark some products still ship; the diamond is canonical.
- Gold is a signature, not a wash: it marks the diamond and thin rules, never a fill or a background.`;
}

function dosAndDonts() {
  return `## Do's and Don'ts

### Do:

- Use semantic tokens for every colour, radius, space, shadow, duration and z-index.
- Design every interactive component for default, hover, focus-visible, active, disabled, loading, error and selected where they apply, at every size it ships.
- Check both themes, at 375px and 1280px, with contrast computed, before calling UI work done.
- Keep Svelte and React twins identical in props, classes and rendering.
- Spend boldness once per surface (the hero CTA, the hub canvas); everything else recedes.
- Carry status with icon plus text, never colour alone.

### Don't:

- Hex, \`rgb()\` or \`hsl()\` literals outside \`packages/tokens/src/tokens.json\`, or \`var(--joy-x, fallback)\` fallbacks (\`scripts/lint-colors.sh\` fails the build).
- Reference primitive ramps (\`--joy-color-navy-500\` and friends) from a component; use the semantic role.
- Tailwind-default SaaS colours: purple primaries, slate neutrals, stock blue links, stock status greens and reds.
- Inverted light mode: white cards on a dark canvas, grey shadows on dark, pure white body text.
- Side-stripe \`border-left\` accents wider than 1px, gradient text, decorative glassmorphism.
- Identical icon + heading + text card grids, a tracked all-caps eyebrow above every section, 01/02/03 markers on content that is not a sequence.
- An arrow glyph appended to link text, \`#111\` standing in for black, middle-dot meta strings.
- Raw OS emoji anywhere; use the SVG icons in \`@joymify/icons\`.
- A flat single-colour hero button with a colour-only hover, a spinner-only loading state, or 32px controls on a phone.`;
}

export function renderDesignMd(m) {
  return `${[frontmatter(m), GENERATED_NOTE, '# Design System: Joymify', overview(m), colors(m), typography(m), elevation(m), components(m), brand(m), dosAndDonts()].join('\n\n')}\n`;
}

const BADGE = { gated: 'parity-gated', both: 'both, not gated', svelte: 'Svelte only', react: 'React only' };

/** `inventory`: [{ name, svelte: bool, react: bool, gated: bool }]. */
export function renderInventory(inventory) {
  const rows = inventory.map((c) => {
    const status = c.svelte && c.react ? (c.gated ? 'gated' : 'both') : c.svelte ? 'svelte' : 'react';
    return [code(c.name), c.svelte ? 'yes' : '-', c.react ? 'yes' : '-', BADGE[status]];
  });
  const gated = inventory.filter((c) => c.gated).length;
  return `${inventory.length} components; ${gated} are held to Svelte/React parity by \`scripts/parity-check.mjs\` (props, classes, ref forwarding).\n\n${table(['Component', 'Svelte', 'React', 'Parity'], rows)}`;
}

export function renderAliases(aliases) {
  const rows = aliases.map((a) => [code(a.alias), a.target ? code(a.target) : 'no direct replacement; pick the semantic role that matches the use']);
  return `${aliases.length} legacy aliases still resolve, marked \`@deprecated\` in \`@joymify/tokens\` types. Replace them with the semantic token.\n\n${table(['Deprecated', 'Use instead'], rows)}`;
}

export function replaceRegion(text, name, body) {
  const begin = `<!-- BEGIN GENERATED:${name} -->`;
  const end = `<!-- END GENERATED:${name} -->`;
  const i = text.indexOf(begin);
  const j = text.indexOf(end);
  if (i === -1 || j === -1 || j < i) throw new Error(`gen-design-md: README is missing the ${begin} / ${end} markers`);
  return `${text.slice(0, i + begin.length)}\n<!-- Generated by scripts/gen-design-md.mjs. Do not edit by hand. -->\n\n${body}\n\n${text.slice(j)}`;
}
